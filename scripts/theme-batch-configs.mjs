function createBatchConfig({
  batchId,
  sourceDirectory,
  sourceArchiveFilename,
  expectedSourceContentSha256,
  expectedSourceArchiveSha256,
  generatedModuleFilename,
  reportFilename,
  exports,
  contracts,
  previousBatch = null,
  semanticTokenCorrections = [],
}) {
  const themeIds = Object.keys(contracts)
  const backgroundIds = themeIds.flatMap((themeId) => contracts[themeId].backgroundIds)
  const existingThemeIds = previousBatch?.registeredThemeIds ?? ORIGINAL_THEME_ID_LIST
  const existingBackgroundIds = previousBatch?.registeredBackgroundIds ?? ORIGINAL_BACKGROUND_ID_LIST
  return Object.freeze({
    batchId,
    sourceDirectory,
    sourceArchiveFilename,
    expectedSourceContentSha256,
    expectedSourceArchiveSha256,
    generatedModuleFilename,
    reportFilename,
    exports,
    contracts,
    existingThemeIds: [...existingThemeIds],
    existingBackgroundIds: [...existingBackgroundIds],
    registeredThemeIds: [...existingThemeIds, ...themeIds],
    registeredBackgroundIds: [...existingBackgroundIds, ...backgroundIds],
    semanticTokenCorrections: [...semanticTokenCorrections],
  })
}

